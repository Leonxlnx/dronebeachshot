import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {pathToFileURL} from 'node:url';
import nodeGles from 'node-gles-webgl2';
import sharp from 'sharp';
import {wrapNativeGL} from './native-gl-compat.mjs';
const root='/workspace/sites/last-light-bay';
const THREE=await import(pathToFileURL(root+'/node_modules/three/build/three.module.js'));
const {createEngine}=await import(pathToFileURL(root+'/src/render/engine.ts'));
const {worldTime}=await import(pathToFileURL(root+'/src/render/materials.ts'));
const moduleFile=path.resolve(process.argv[2]||root+'/src/world/atmosphere.ts');
const {createAtmosphere}=await import(pathToFileURL(moduleFile));
const output=path.resolve(process.argv[3]||'sky-only.png');
const width=Number(process.argv[4]||480),height=Math.round(width*9/16);
const gl=wrapNativeGL(nodeGles.createWebGLRenderingContext({width,height,majorVersion:3,minorVersion:0}));
const canvas={width,height,style:{},addEventListener(){},removeEventListener(){},setAttribute(){},getContext(type){return type==='webgl2'?gl:null;}};gl.canvas=canvas;
const {renderer,scene,camera,shaderErrors}=createEngine(canvas);
renderer.setPixelRatio(1);renderer.setSize(width,height,false);
camera.aspect=width/height;camera.position.set(10,4,-28);camera.lookAt(-365,80,-940);camera.updateProjectionMatrix();
worldTime.value=17;
const atmosphere=createAtmosphere(renderer);scene.add(atmosphere.group);
const start=performance.now();
atmosphere.update(renderer,camera.position,17);
await renderer.compileAsync(scene,camera);renderer.render(scene,camera);gl.finish();
if(shaderErrors.length)throw Error(shaderErrors.join('\n'));
const pixels=new Uint8Array(width*height*4);gl.readPixels(0,0,width,height,gl.RGBA,gl.UNSIGNED_BYTE,pixels);
const glError=gl.getError();if(glError!==gl.NO_ERROR)throw Error('Native GL error '+glError);
await fs.mkdir(path.dirname(output),{recursive:true});
await sharp(pixels,{raw:{width,height,channels:4}}).flip().removeAlpha().png().toFile(output);
const cloudModuleFile=moduleFile.replace('atmosphere','clouds');
const report={method:'Native ANGLE production createAtmosphere; sky-only investigation, not browser QA',module:moduleFile,moduleSHA256:crypto.createHash('sha256').update(await fs.readFile(moduleFile)).digest('hex'),cloudModuleFile,cloudModuleSHA256:crypto.createHash('sha256').update(await fs.readFile(cloudModuleFile)).digest('hex'),width,height,time:17,camera:{position:camera.position.toArray(),target:[-365,80,-940],fov:camera.fov},shaderErrors,glError,renderMilliseconds:Math.round(performance.now()-start),renderer:gl.getParameter(gl.RENDERER)};
await fs.writeFile(output+'.json',JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
atmosphere.dispose();renderer.dispose();gl.destroy();
